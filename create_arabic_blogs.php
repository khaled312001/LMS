foreach ($translations as $enId => $data) {
    $en = Blog::find($enId);
    if (!$en) { echo "  ⚠️  English blog {$enId} not found\n"; continue; }

    // Check if Arabic version already exists
    $existing = Blog::where('pair_id', $enId)->where('language', 'arabic')->first();
    if ($existing) {
        echo "  ℹ️  Arabic twin of {$enId} already exists (ID {$existing->id})\n";
        continue;
    }

    $ar = new Blog();
    $ar->user_id     = $en->user_id;
    $ar->category_id = $en->category_id;
    $ar->title       = $data['title'];
    $ar->slug        = 'ar-' . $en->slug;
    $ar->description = $data['description'];
    $ar->thumbnail   = $en->thumbnail;
    $ar->banner      = $en->banner;
    $ar->keywords    = $data['keywords'];
    $ar->is_popular  = $en->is_popular;
    $ar->status      = 1;
    $ar->language    = 'arabic';
    $ar->pair_id     = $enId;
    $ar->save();

    // Link English back to Arabic
    $en->pair_id  = $ar->id;
    $en->language = 'english';
    $en->save();

    echo "  ✅ Blog {$enId} → Arabic twin {$ar->id}: " . mb_substr($data['title'], 0, 40) . "…\n";
}

